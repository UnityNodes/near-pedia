import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { getDb } from '../lib/db';

const OUT = path.join(process.cwd(), 'lib', 'db-rows.ts');

type ColumnInfo = { name: string; type: string; notnull: number; pk: number };

function tsType(declared: string): string {
  switch (declared.toUpperCase()) {
    case 'TEXT': return 'string';
    case 'INTEGER': return 'number';
    case 'REAL': return 'number';
    case 'BLOB': return 'Buffer';
    default: return 'unknown';
  }
}

function interfaceName(table: string): string {
  return table
    .split('_')
    .map(p => p.charAt(0).toUpperCase() + p.slice(1))
    .join('') + 'Row';
}

function propName(col: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(col) ? col : JSON.stringify(col);
}

export function renderDbRows(): string {
  const db = getDb();
  const tables = db.prepare(`
    SELECT name FROM sqlite_master
    WHERE type='table' AND name NOT LIKE 'sqlite_%'
    ORDER BY name
  `).all() as { name: string }[];

  const blocks: string[] = [];
  const names: string[] = [];

  for (const { name } of tables) {
    const cols = db.prepare(`PRAGMA table_info("${name}")`).all() as ColumnInfo[];
    if (!cols.length) continue;

    const iface = interfaceName(name);
    names.push(`  ${JSON.stringify(name)}: ${iface};`);

    const fields = cols.map(c => {
      const base = tsType(c.type);
      const nullable = c.notnull === 0 && c.pk === 0;
      return `  ${propName(c.name)}: ${base}${nullable ? ' | null' : ''};`;
    });

    blocks.push(`export interface ${iface} {\n${fields.join('\n')}\n}`);
  }

  return [
    '// GENERATED by scripts/generate-db-rows.ts. Do not edit by hand.',
    '//',
    '// One interface per table, derived from PRAGMA table_info so it cannot drift',
    '// from the schema by being edited independently. Columns with no declared',
    '// type (FTS5 virtual tables) become `unknown` on purpose: SQLite gives them',
    '// BLOB affinity and they can hold anything, so the caller must narrow.',
    '//',
    '// A column is nullable unless it is NOT NULL or part of the primary key.',
    '// better-sqlite3 `.get()` returns undefined when nothing matches, so call',
    '// sites should cast to `Row | undefined`, not `Row`.',
    '//',
    '// scripts/check-db-rows.ts re-renders this and fails on any difference.',
    '',
    ...blocks.map(b => b + '\n'),
    'export interface DbRowByTable {',
    ...names,
    '}',
    '',
  ].join('\n');
}

function main() {
  const out = renderDbRows();
  writeFileSync(OUT, out);
  const tables = out.match(/^export interface \w+Row \{/gm)?.length ?? 0;
  console.log(`[generate-db-rows] wrote ${OUT} (${tables} tables, ${out.split('\n').length} lines)`);
}

if (process.argv[1] && process.argv[1].endsWith('generate-db-rows.ts')) main();
